export function translate(locale: Locale, value: string) {
  if (locale === "tw") return value;
  return en[value as keyof typeof en] ?? value;
}

export function translateDeep<T>(locale: Locale, value: T): T {
  if (locale === "tw") return value;
  if (typeof value === "string") return translate(locale, value) as T;
  if (Array.isArray(value)) return value.map((item) => translateDeep(locale, item)) as T;
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, translateDeep(locale, item)]),
    ) as T;
  }
  return value;
}
